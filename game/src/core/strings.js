/**
 * The foundation's own bilingual strings: loading and fatal layers, save and journey-code messages, glossary
 * terms, stats, difficulty, and the display names of every catalog id (GDD names) so that stand-in content is
 * named in both languages. Owning packages re-register their own names with i18n.addStrings (later tables win).
 * Hebrew UI text never starts with a bare imperative (ART_UX 7.1): infinitives and nouns only.
 * @module core/strings
 */

/**
 * Build `{ he, en }` tables from rows of [key, en, he].
 * @param {Array<[string, string, string]>} rows
 * @returns {{ he:Record<string, string>, en:Record<string, string> }}
 */
function tables(rows) {
  const he = {};
  const en = {};
  for (const [key, e, h] of rows) {
    en[key] = e;
    he[key] = h;
  }
  return { he, en };
}

